-- Enable UUID generation extension
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ----------------------------------------------------------------------------
-- 1. TABLE: users
-- Stores both students ('maba') and committee members ('admin').
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT UNIQUE NOT NULL,
  nama_ksatria TEXT NOT NULL,
  nim TEXT UNIQUE NOT NULL,
  faksi TEXT NOT NULL, -- Major / Class / Division (e.g., 'Teknik Informatika / Hardware')
  role TEXT NOT NULL DEFAULT 'maba' CHECK (role IN ('maba', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_role ON public.users(role);
CREATE INDEX IF NOT EXISTS idx_users_nim ON public.users(nim);

-- ----------------------------------------------------------------------------
-- 2. TABLE: absensi_sessions
-- Stores attendance PIN ("Rune Rahasia") sessions generated by committee.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.absensi_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  rune_code TEXT UNIQUE NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_absensi_sessions_active ON public.absensi_sessions(is_active);
CREATE INDEX IF NOT EXISTS idx_absensi_sessions_rune_code ON public.absensi_sessions(rune_code);

-- ----------------------------------------------------------------------------
-- 3. TABLE: absensi_logs
-- Logs student attendance submissions linked to an absensi_session.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.absensi_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id UUID NOT NULL REFERENCES public.absensi_sessions(id) ON DELETE CASCADE,
  maba_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'HADIR' CHECK (status IN ('HADIR', 'IZIN', 'SAKIT', 'ALPHA')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (session_id, maba_id)
);

CREATE INDEX IF NOT EXISTS idx_absensi_logs_session ON public.absensi_logs(session_id);
CREATE INDEX IF NOT EXISTS idx_absensi_logs_maba ON public.absensi_logs(maba_id);

-- ----------------------------------------------------------------------------
-- 4. TABLE: quizzes
-- Multiple-choice quiz bank for the /arena (maba) and /kuis (admin).
-- `options` stores JSON, e.g. {"A": "...", "B": "...", "C": "...", "D": "..."}
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.quizzes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  question TEXT NOT NULL,
  options JSONB NOT NULL,
  correct_answer TEXT NOT NULL CHECK (correct_answer IN ('A', 'B', 'C', 'D')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 5. TABLE: grades
-- Gradebook records for each student ('maba') managed in /rekap-nilai:
-- - Kehadiran: total 8 pertemuan (boolean[8] / skor 0-100)
-- - Keaktifan: total 8 pertemuan (number[8] / rata-rata 0-100)
-- - Tugas: total 3 tugas (number[3] / rata-rata 0-100)
-- - Ujian: nilai ujian akhir (0-100)
-- - Nilai Akhir: rekap gabungan dari Kehadiran + Keaktifan + Tugas + Ujian
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.grades (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  maba_id UUID UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  kehadiran_pertemuan JSONB NOT NULL DEFAULT '[true,true,true,true,true,true,true,true]'::jsonb, -- 8 pertemuan
  keaktifan_pertemuan JSONB NOT NULL DEFAULT '[80,80,80,80,80,80,80,80]'::jsonb,                 -- 8 pertemuan (0-100 per pertemuan)
  tugas_detail JSONB NOT NULL DEFAULT '[80,80,80]'::jsonb,                                        -- 3 tugas (Tugas 1, 2, 3)
  kehadiran NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (kehadiran >= 0 AND kehadiran <= 100),
  keaktifan NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (keaktifan >= 0 AND keaktifan <= 100),
  tugas NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (tugas >= 0 AND tugas <= 100),
  ujian NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (ujian >= 0 AND ujian <= 100),
  nilai_akhir NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (nilai_akhir >= 0 AND nilai_akhir <= 100),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_grades_nilai_akhir ON public.grades(nilai_akhir DESC);

-- Trigger function to automatically compute `nilai_akhir`
-- Formula: 20% Kehadiran (8 pertemuan) + 20% Keaktifan (8 pertemuan) + 30% Tugas (3 tugas) + 30% Ujian
CREATE OR REPLACE FUNCTION public.calculate_nilai_akhir()
RETURNS TRIGGER AS $$
BEGIN
  NEW.nilai_akhir := ROUND(
    (COALESCE(NEW.kehadiran, 0) * 0.20) +
    (COALESCE(NEW.keaktifan, 0) * 0.20) +
    (COALESCE(NEW.tugas, 0) * 0.30) +
    (COALESCE(NEW.ujian, 0) * 0.30),
    2
  );
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_calculate_nilai_akhir ON public.grades;
CREATE TRIGGER trg_calculate_nilai_akhir
BEFORE INSERT OR UPDATE ON public.grades
FOR EACH ROW
EXECUTE FUNCTION public.calculate_nilai_akhir();

